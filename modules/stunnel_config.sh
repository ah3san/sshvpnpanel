        echo -e "${C_BOLD}Tunnel Management:${C_RESET}"
        echo "  5. Add Tunnel"
        echo "  6. Remove Tunnel"
        echo "  7. Enable/Disable Tunnel"
        echo "  8. List Tunnels"
        echo "  9. Tunnel Details"
        echo
        echo -e "${C_BOLD}Certificate Management:${C_RESET}"
        echo " 10. Generate Self-Signed Certificate"
        echo " 11. Generate CA Certificate"
        echo " 12. Sign Certificate with CA"
        echo " 13. List Certificates"
        echo " 14. Renew Certificate"
        echo " 15. Check Expiring Certificates"
        echo
        echo -e "${C_BOLD}Monitoring:${C_RESET}"
        echo " 16. View Traffic Stats"
        echo " 17. Start/Stop Watchdog"
        echo "  0. Back to Main Menu"
        echo

        local choice
        choice="$(read_int "Select option" 0 17)"

        case "${choice}" in
            1) stunnel_start; read -rp $'\nPress Enter to continue...' ;;
            2) stunnel_stop; read -rp $'\nPress Enter to continue...' ;;
            3) stunnel_restart; read -rp $'\nPress Enter to continue...' ;;
            4) stunnel_reload; read -rp $'\nPress Enter to continue...' ;;
            5) _menu_add_tunnel ;;
            6) _menu_remove_tunnel ;;
            7) _menu_toggle_tunnel ;;
            8) list_tunnels; read -rp $'\nPress Enter to continue...' ;;
            9) _menu_tunnel_detail ;;
            10) _menu_gen_self_signed ;;
            11) _menu_gen_ca ;;
            12) _menu_sign_cert ;;
            13) list_certificates; read -rp $'\nPress Enter to continue...' ;;
            14) _menu_renew_cert ;;
            15) check_expiring_certs; read -rp $'\nPress Enter to continue...' ;;
            16) show_stunnel_stats; read -rp $'\nPress Enter to continue...' ;;
            17) _menu_watchdog ;;
            0) return 0 ;;
        esac
    done
}

_menu_add_tunnel() {
    clear_screen
    print_header "Add Stunnel Tunnel"

    local name
    read_input "Tunnel name (e.g., ssh-ssl)" "" name
    [[ -z "${name}" ]] && return

    local accept
    read_input "Accept address (e.g., 0.0.0.0:443)" "0.0.0.0:443" accept
    accept="${accept:-0.0.0.0:443}"

    local connect
    read_input "Connect to (e.g., 127.0.0.1:22)" "127.0.0.1:22" connect
    connect="${connect:-127.0.0.1:22}"

    echo "TLS versions: 1.TLSv1.2  2.TLSv1.3  3.TLSv1.2,TLSv1.3"
    local tls_choice
    tls_choice="$(read_int "TLS version" 1 3 "2")"
    local tls_versions=("TLSv1.2" "TLSv1.3" "TLSv1.2,TLSv1.3")
    local tls="${tls_versions[$((tls_choice-1))]}"

    local cert_path
    read_input "Certificate file path (empty to auto-generate)" "" cert_path

    echo
    add_tunnel "${name}" "${accept}" "${connect}" "${cert_path}" "" "${tls}"
    read -rp $'\nPress Enter to continue...'
}

_menu_remove_tunnel() {
    list_tunnels
    echo
    local name
    read_input "Tunnel name to remove (or 'cancel')" "" name
    [[ "${name}" == "cancel" || -z "${name}" ]] && return
    remove_tunnel "${name}"
    read -rp $'\nPress Enter to continue...'
}

_menu_toggle_tunnel() {
    list_tunnels
    echo
    local name
    read_input "Tunnel name" "" name
    [[ -z "${name}" ]] && return

    if ! tunnel_exists "${name}"; then
        print_error "Tunnel '${name}' not found"
    else
        local enabled
        enabled="$(config_get "$(tunnel_config_file "${name}")" "ENABLED" "yes")"
        if [[ "${enabled}" == "yes" ]]; then
            disable_tunnel "${name}"
        else
            enable_tunnel "${name}"
        fi
    fi
    read -rp $'\nPress Enter to continue...'
}

_menu_tunnel_detail() {
    local name
    read_input "Tunnel name" "" name
    [[ -z "${name}" ]] && return
    show_tunnel_detail "${name}"
    read -rp $'\nPress Enter to continue...'
}

_menu_gen_self_signed() {
    clear_screen
    print_header "Generate Self-Signed Certificate"

    local cn
    read_input "Common Name (hostname or domain)" "stunnel" cn
    cn="${cn:-stunnel}"

    local cert_file="${STUNNEL_CERTS_DIR}/${cn}.crt"
    local key_file="${STUNNEL_CERTS_DIR}/${cn}.key"

    if [[ -f "${cert_file}" ]]; then
        confirm "Certificate '${cn}' already exists. Overwrite?" "no" || return
    fi

    local days
    days="$(read_int "Validity in days" 1 3650 "${DEFAULT_CERT_DAYS:-365}")"

    generate_self_signed_cert "${cn}" "${cert_file}" "${key_file}" "${days}"
    read -rp $'\nPress Enter to continue...'
}

_menu_gen_ca() {
