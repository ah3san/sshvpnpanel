_menu_watchdog() {
    echo
    echo "  1. Start Watchdog"
    echo "  2. Stop Watchdog"
    local choice
    choice="$(read_int "Select" 1 2)"
    if [[ "${choice}" -eq 1 ]]; then
        stunnel_watchdog_start
    else
        stunnel_watchdog_stop
    fi
    read -rp $'\nPress Enter to continue...'
}
