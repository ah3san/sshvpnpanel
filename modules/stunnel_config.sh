# TRAFFIC MONITORING
# =============================================================================

show_stunnel_stats() {
    clear_screen
    print_header "Stunnel Traffic Statistics"

    local log_file="${STUNNEL_LOG_FILE:-/var/log/stunnel4/stunnel4.log}"

    if [[ ! -f "${log_file}" ]]; then
        print_info "No Stunnel log file found at ${log_file}"
        return
    fi

    # Count connections from log
    local total_connections
    total_connections="$(grep -c "Connection from" "${log_file}" 2>/dev/null || echo "0")"
    local today_connections
    today_connections="$(grep "$(date '+%Y.%m.%d')" "${log_file}" 2>/dev/null | \
        grep -c "Connection from" || echo "0")"
    local error_count
    error_count="$(grep -c "Error\|error" "${log_file}" 2>/dev/null || echo "0")"

    echo -e "\n${C_BOLD}Summary Statistics${C_RESET}"
    print_separator 40
    printf "  %-30s %s\n" "Total connections:" "${total_connections}"
    printf "  %-30s %s\n" "Today's connections:" "${today_connections}"
    printf "  %-30s %s\n" "Error count:" "${error_count}"

    echo -e "\n${C_BOLD}Recent Log Entries${C_RESET}"
    print_separator 40
    tail -20 "${log_file}" | while IFS= read -r line; do
        local color="${C_DIM}"
        [[ "${line}" =~ [Ee]rror|WARN ]] && color="${C_WARNING}"
        [[ "${line}" =~ [Ee]mergency|EMERG ]] && color="${C_ERROR}"
        echo -e "  ${color}${line}${C_RESET}"
    done
}

